def detect_language():
    try:
        name = locale.getlocale()[0]
    except ValueError:
        name = None
    return "es" if name and name.lower().startswith(("es", "spanish")) else "en"


class Translator:
    def __init__(self, lang=None):
        self.lang = lang if lang in TEXTS else detect_language()

    def __call__(self, key, **kw):
        text = TEXTS[self.lang][key]
        return text.format(**kw) if kw else text

    def param_label(self, key):
        es, _, en, _ = PARAM_TEXTS[key]
        return es if self.lang == "es" else en

    def param_help(self, key):
        _, es, _, en = PARAM_TEXTS[key]
        return es if self.lang == "es" else en
